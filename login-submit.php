          <span>Database stores hash only</span>
          <span>Demo data only</span>
        </div>
      </div>

      <section class="login-panel result-panel" aria-label="Submitted demo values">
        <h2>Submitted Demo Values</h2>
        <dl class="result-list">
          <div>
            <dt>Email</dt>
            <dd><?php echo $safeEmail ?: 'Not provided'; ?></dd>
          </div>
          <div>
            <dt>Password mask</dt>
            <dd><?php echo $safeMaskedPassword ?: 'Not provided'; ?></dd>
          </div>
          <div>
            <dt>Password length</dt>
            <dd><?php echo $passwordLength; ?> characters</dd>
          </div>
